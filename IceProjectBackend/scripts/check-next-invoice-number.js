/*
  Prints the next invoice number that will be generated by the system
  without creating any data. Reads STARTING_INVOICE_NUMBER baseline.

  Usage (PowerShell example):
    $env:MONGO_URI = "<your-mongo-uri>"
    # optional override
    # $env:STARTING_INVOICE_NUMBER = "20350000"
    node scripts/check-next-invoice-number.js
*/

const mongoose = require('mongoose');
const path = require('path');

// Ensure we can require models
const Invoice = require(path.join(__dirname, '..', 'src', 'models', 'Invoice'));

const MONGO_URI = process.env.MONGO_URI || process.env.DATABASE_URL || process.env.MONGODB_URI;
if (!MONGO_URI) {
  console.error('Missing MONGO_URI (or DATABASE_URL/MONGODB_URI) environment variable.');
  process.exit(1);
}

(async () => {
  try {
    await mongoose.connect(MONGO_URI, {
      autoIndex: false,
      serverSelectionTimeoutMS: 10000,
    });

    // Re-implement the same logic used inside the model to report details
    const STARTING_INVOICE_NUMBER = parseInt(process.env.STARTING_INVOICE_NUMBER || '20350000', 10);

    const lastInvoice = await Invoice.findOne({ invoiceNumber: { $type: 'number', $ne: null } })
      .sort({ invoiceNumber: -1 })
      .lean();

    let lastNumber = 0;
    if (lastInvoice && typeof lastInvoice.invoiceNumber === 'number' && !isNaN(lastInvoice.invoiceNumber)) {
      lastNumber = lastInvoice.invoiceNumber;
    } else {
      const count = await Invoice.countDocuments();
      lastNumber = count;
    }

    const baselineAppliedFrom = Math.max(lastNumber, STARTING_INVOICE_NUMBER);
    const nextNumber = baselineAppliedFrom + 1;

    console.log(JSON.stringify({
      baseline: STARTING_INVOICE_NUMBER,
      lastInvoiceNumber: lastInvoice?.invoiceNumber || null,
      derivedLastNumber: lastNumber,
      baselineAppliedFrom,
      nextNumber,
    }, null, 2));
  } catch (err) {
    console.error('Error checking next invoice number:', err);
    process.exit(1);
  } finally {
    await mongoose.disconnect();
  }
})();
